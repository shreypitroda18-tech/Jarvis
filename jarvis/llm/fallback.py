def extract_error_info(exc: Exception) -> Tuple[Optional[int], Optional[str], str]:
    """Extracts (status_code, error_code, error_message) cleanly and scrubs secrets."""
    status_code = getattr(exc, "status_code", None)
    err_code = getattr(exc, "code", None)
    body = getattr(exc, "body", None)
    msg = ""

    if isinstance(body, dict) and "error" in body and isinstance(body["error"], dict):
        err_dict = body["error"]
        msg = err_dict.get("message") or ""
        if not err_code:
            err_code = err_dict.get("code")
    if not msg:
        msg = getattr(exc, "message", None) or str(exc)

    clean_msg = scrub_secrets(str(msg)).replace("\r", " ").replace("\n", " ").strip()
    return status_code, err_code, clean_msg[:300]


def extract_retry_after(exc: Exception) -> Optional[int]:
    """Extracts retry delay in seconds from HTTP headers or reset indicators if present."""
    resp = getattr(exc, "response", None)
    headers = getattr(resp, "headers", {}) if resp else {}
    if hasattr(headers, "get"):
        ra = headers.get("retry-after")
        if ra:
            try:
                return max(1, int(float(ra)))
            except Exception:
                pass
        reset_req = headers.get("x-ratelimit-reset-requests") or headers.get("x-ratelimit-reset-tokens")
        if reset_req:
            try:
                secs = 0
                m_match = re.search(r"(\d+(?:\.\d+)?)\s*m", str(reset_req))
                s_match = re.search(r"(\d+(?:\.\d+)?)\s*s", str(reset_req))
                if m_match:
                    secs += int(float(m_match.group(1)) * 60)
                if s_match:
                    secs += int(float(s_match.group(1)))
                if secs > 0:
                    return secs
                return int(float(reset_req))
            except Exception:
                pass
    return None


def extract_text_from_dict(data: Any) -> Optional[str]:
    """Extracts human-readable text from a dictionary or structure if present."""
    if isinstance(data, str):
        cleaned = data.strip()
        if cleaned and not cleaned.startswith("{") and not cleaned.startswith("["):
            return cleaned
        return None

    if not isinstance(data, dict):
        return None

    # Priority text fields often generated by models like llama3.2:3b
    priority_keys = [
        "joke", "text", "message", "content", "response", "answer",
        "output", "result", "body", "prompt", "say", "speech"
    ]
    for k in priority_keys:
        val = data.get(k)
        if isinstance(val, str) and val.strip():
            return val.strip()

    # Structural keys that should never be mistaken for human conversational text
    excluded_keys = {"name", "tool", "function", "id", "type", "call_id"}
    for k, val in data.items():
        if k.lower() in excluded_keys:
            continue
        if isinstance(val, str) and val.strip() and len(val.strip()) > 3:
            return val.strip()

    return None


def parse_pseudo_tool_call(content: str) -> Optional[Tuple[str, Dict[str, Any], Optional[str]]]:
    """
    Checks if text content is formatted as a pseudo-tool-call JSON object.
    Returns (tool_name, arguments_dict, extracted_text) or None.
    """
    if not content or not content.strip():
        return None

    cleaned = content.strip()
    # Strip markdown code blocks
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
        cleaned = re.sub(r"\s*```$", "", cleaned)
        cleaned = cleaned.strip()

    match = re.search(r"\{.*\}", cleaned, re.DOTALL)
    if not match:
        return None

    try:
        data = json.loads(match.group(0))
        if not isinstance(data, dict):
            return None
    except Exception:
        return None

    name = data.get("name") or data.get("function") or data.get("tool")
    if isinstance(name, dict):
        name = name.get("name")

    raw_args = data.get("parameters") or data.get("arguments") or data.get("args") or {}
    if isinstance(raw_args, str):
        try:
            raw_args = json.loads(raw_args)
        except Exception:
            raw_args = {"text": raw_args}
    elif not isinstance(raw_args, dict):
        raw_args = {"value": raw_args}

    extracted_text = extract_text_from_dict(raw_args) or extract_text_from_dict(data)

    outside = cleaned[:match.start()].strip() + " " + cleaned[match.end():].strip()
    outside = outside.strip()
    if outside and not extracted_text:
        extracted_text = outside

    if not name or not isinstance(name, str):
        if extracted_text:
            return ("_unnamed_json_", raw_args, extracted_text)
        return None

    return (name.strip(), raw_args, extracted_text)


def clean_final_reply(reply: Optional[str]) -> str:
    """Ensures raw JSON is never shown to the user."""
    if not reply or not reply.strip():
        return "Action completed, sir."

    cleaned = reply.strip()
    # Strip markdown block if it surrounds JSON
    if cleaned.startswith("```"):
        stripped = re.sub(r"^```(?:json)?\s*", "", cleaned)
        stripped = re.sub(r"\s*```$", "", stripped).strip()
        if stripped.startswith("{") and stripped.endswith("}"):
            cleaned = stripped

    if cleaned.startswith("{") and cleaned.endswith("}"):
        try:
            data = json.loads(cleaned)
            extracted = extract_text_from_dict(data)
            if extracted:
                return extracted
            return "At your service, sir. How may I assist you?"
        except Exception:
            pass

    pseudo = parse_pseudo_tool_call(cleaned)
    if pseudo:
        _, _, extracted_text = pseudo
        if extracted_text:
            return extracted_text
        return "At your service, sir. How may I assist you?"

    return cleaned


class FallbackManager:
    """Orchestrates multi-provider fallback with automatic cooldown and tool execution."""

    def __init__(
        self,
        system_instruction: str,
        tools: List[Callable],
    ):
        self.system_instruction = system_instruction
        self.tools = tools
        self.tools_map: Dict[str, Callable] = {t.__name__: t for t in tools}
        self.cloud_tools_schema = generate_tools_schema(tools)
        self.local_tools_schema = generate_tools_schema(
            [t for t in tools if t.__name__ not in COMPUTER_CONTROL_TOOL_NAMES]
        )
        self.subset_tools_schema = generate_tools_schema(
            [t for t in tools if t.__name__ in CORE_SUBSET_TOOL_NAMES]
        )
        self.tools_schema = self.cloud_tools_schema

        self.history = NeutralHistoryManager(system_instruction=system_instruction)
        self.providers: List[BaseLLMProvider] = []
        self.blocked_until: Dict[str, datetime] = {}
        self._ollama_warmed: bool = False
        self._init_providers()

    def _init_providers(self) -> None:
        """Instantiates providers based on config.llm_provider and config.llm_fallbacks."""
        provider_names = [config.llm_provider] + [
            fb for fb in config.llm_fallbacks if fb != config.llm_provider
        ]

        self.providers = []
        for p_name in provider_names:
            p_clean = p_name.lower().strip()
            if p_clean == "groq":
                self.providers.append(
                    OpenAICompatibleProvider(
                        name="groq",
                        base_url="https://api.groq.com/openai/v1",
                        api_key=config.groq_api_key,
                        model_name=config.groq_model,
                    )
                )
            elif p_clean == "ollama":
                self.providers.append(
                    OpenAICompatibleProvider(
                        name="ollama",
                        base_url=config.ollama_base_url,
                        api_key=config.ollama_api_key,
                        model_name=config.ollama_model,
                    )
                )
            elif p_clean == "gemini":
                from jarvis.llm.gemini_provider import GeminiProvider
                self.providers.append(
                    GeminiProvider(
                        api_key=config.gemini_api_key,
                        model_name=config.gemini_model,
                    )
                )
            else:
                logger.warning(f"Unknown provider '{p_name}' requested in settings.")

    def is_provider_blocked(self, provider_name: str) -> bool:
        """Checks if a provider is currently under an active cooldown period."""
        if provider_name in self.blocked_until:
            if datetime.now() < self.blocked_until[provider_name]:
                return True
            else:
                # Cooldown expired, probe again
                del self.blocked_until[provider_name]
                logger.info(f"Cooldown expired for {provider_name}. Probing provider again.")
        return False

    def mark_cooldown(self, provider_name: str, seconds: int) -> None:
        """Sets a cooldown timer for a blocked provider."""
        expiry = datetime.now() + timedelta(seconds=seconds)
        self.blocked_until[provider_name] = expiry
        logger.info(f"Marked cooldown for {provider_name} until {expiry.strftime('%H:%M:%S')}")

    def is_daily_quota_error(self, error_message: str) -> bool:
        """Determines if a rate limit error is a daily quota exhaustion versus a per-minute limit."""
        msg = error_message.lower()
        daily_indicators = [
            "daily", "day", "rpd", "tpd", "requests per day", "tokens per day",
            "exceeded your current quota", "quota exhausted", "monthly", "credit"
        ]
        return any(ind in msg for ind in daily_indicators)

    def execute_turn(self, user_input: str) -> str:
        """
        Executes a complete user turn with automatic fallback across providers,
        strictly enforces registered-only tool execution, parses pseudo-JSON calls,
        and ensures raw JSON is never shown to the user.
        """
        self.history.add_user_message(user_input)
        max_tool_iterations = 6

        fallback_notified = False
        unregistered_retried = False

        for iteration in range(max_tool_iterations):
            eligible_providers = [p for p in self.providers if not self.is_provider_blocked(p.name)]
            if not eligible_providers:
                return self._build_all_blocked_message()

            response: Optional[ProviderResponse] = None
            active_provider: Optional[BaseLLMProvider] = None

            for idx, provider in enumerate(eligible_providers):
                try:
                    messages = self.history.to_openai_format()
                    response = self._call_provider_with_retry(provider, messages)
                    active_provider = provider
                    break
                except Exception as exc:
                    status_code, err_code, clean_msg = extract_error_info(exc)
                    retry_sec = extract_retry_after(exc)
                    is_daily = self.is_daily_quota_error(clean_msg)

                    next_provider = eligible_providers[idx + 1] if idx + 1 < len(eligible_providers) else None
                    next_name = next_provider.name.capitalize() if next_provider else "none"

                    if is_daily:
                        cooldown = retry_sec or config.llm.daily_quota_cooldown_seconds
                        self.mark_cooldown(provider.name, cooldown)
                        log_line = f"{provider.name.capitalize()} quota hit, using {next_name} (HTTP 429 daily, reset in {cooldown}s)"
                        logger.warning(log_line, extra={"is_fallback": True, "fallback_reason": log_line})
                    elif status_code == 429 or isinstance(exc, RateLimitError) or "429" in clean_msg:
                        cooldown = retry_sec or config.llm.default_cooldown_seconds
                        self.mark_cooldown(provider.name, cooldown)
                        log_line = f"{provider.name.capitalize()} rate limit reached, using {next_name} (HTTP 429, retry in {cooldown}s)"
                        logger.warning(log_line, extra={"is_fallback": True, "fallback_reason": log_line})
                    elif status_code in (401, 403, 404):
                        # Configuration / Authentication error: NO COOLDOWN
                        log_line = f"{provider.name.capitalize()} configuration error (HTTP {status_code}, code={err_code}): {clean_msg}, using {next_name}"
                        logger.error(log_line, extra={"is_fallback": True, "fallback_reason": log_line})
                    elif status_code == 400:
                        # Bad request (tool use or invalid request - NOT a connection error)
                        self.mark_cooldown(provider.name, config.llm.default_cooldown_seconds)
                        log_line = f"{provider.name.capitalize()} bad request (HTTP 400, code={err_code}): {clean_msg}, using {next_name}"
                        logger.warning(log_line, extra={"is_fallback": True, "fallback_reason": log_line})
                    elif status_code == 413:
                        # Payload Too Large
                        self.mark_cooldown(provider.name, config.llm.default_cooldown_seconds)
                        log_line = f"{provider.name.capitalize()} payload too large (HTTP 413): {clean_msg}, using {next_name}"
                        logger.warning(log_line, extra={"is_fallback": True, "fallback_reason": log_line})
                    else:
                        # 5xx server or connection errors
                        self.mark_cooldown(provider.name, config.llm.default_cooldown_seconds)
                        log_line = f"{provider.name.capitalize()} connection error ({exc.__class__.__name__}, HTTP {status_code or 'CONN'}), using {next_name}: {clean_msg}"
                        logger.warning(log_line, extra={"is_fallback": True, "fallback_reason": log_line})

                    if config.llm.notify_on_fallback and not fallback_notified and next_provider:
                        fallback_notified = True

            if not response or not active_provider:
                return self._build_all_blocked_message()

            # Handle models (like llama3.2:3b) that emit JSON pseudo-tool-calls in content
            if not response.tool_calls and response.content:
                pseudo = parse_pseudo_tool_call(response.content)
                if pseudo:
                    p_name, p_args, p_text = pseudo
                    if p_name in self.tools_map:
                        # Legitimate registered tool emitted as JSON in text
                        response.tool_calls = [ToolCall(id=f"call_{p_name}", name=p_name, arguments=p_args)]
                        response.content = None
                    else:
                        # Unregistered tool name (e.g. print_joke)
                        logger.warning(f"Model generated pseudo-tool '{p_name}', which is not registered. Ignoring tool.")
                        if p_text:
                            # Use extracted text content (such as the joke) as the reply
                            reply = clean_final_reply(p_text)
                            if fallback_notified and config.llm.notify_on_fallback:
                                reply = f"[Using {active_provider.name.capitalize()}] {reply}"
                            return reply
                        elif not unregistered_retried:
                            unregistered_retried = True
                            self.history.add_user_message(
                                f"System note: The tool '{p_name}' does not exist. Please respond directly in plain English."
                            )
                            continue
                        else:
                            return "At your service, sir. How may I assist you?"

            # Separate native tool calls into registered and unregistered
            valid_tool_calls: List[ToolCall] = []
            unregistered_text: Optional[str] = None

            for tc in response.tool_calls:
                if tc.name in self.tools_map:
                    valid_tool_calls.append(tc)
                else:
                    # An unregistered tool must NEVER be executed
                    logger.warning(f"Tool '{tc.name}' is not registered. Execution blocked.")
                    extracted = extract_text_from_dict(tc.arguments)
                    if extracted and not unregistered_text:
                        unregistered_text = extracted

            # If the model called ONLY unregistered tool(s)
            if response.tool_calls and not valid_tool_calls:
                if unregistered_text:
                    reply = clean_final_reply(unregistered_text)
                    if fallback_notified and config.llm.notify_on_fallback:
                        reply = f"[Using {active_provider.name.capitalize()}] {reply}"
                    return reply
                elif not unregistered_retried:
                    unregistered_retried = True
                    self.history.add_user_message(
                        "System note: That tool is not registered. Please respond directly in conversational text."
                    )
                    continue
                else:
                    return "At your service, sir. How may I assist you?"

            # Record assistant turn in neutral history with ONLY valid tool calls
            tc_dicts = [
                {"id": tc.id, "name": tc.name, "arguments": tc.arguments}
                for tc in valid_tool_calls
            ] if valid_tool_calls else None

            self.history.add_assistant_message(
                content=response.content,
                tool_calls=tc_dicts,
            )

            # If no valid tools to call, return the clean text response
            if not valid_tool_calls:
                reply = clean_final_reply(response.content)
                if fallback_notified and config.llm.notify_on_fallback:
                    reply = f"[Using {active_provider.name.capitalize()}] {reply}"
                return reply

            # Execute ONLY registered tools (unregistered are guaranteed absent)
            for tc in valid_tool_calls:
                tool_func = self.tools_map[tc.name]
                if active_provider and active_provider.name.lower() == "ollama" and tc.name in COMPUTER_CONTROL_TOOL_NAMES:
                    explanation = (
                        "Computer and browser automation tools are disabled on local Ollama models "
                        "because small local language models lack reliable visual-spatial grounding and multi-step UI reasoning required for safe desktop operation."
                    )
                    self.history.add_tool_response(tc.id, tc.name, explanation)
                    return explanation

                try:
                    res = tool_func(**tc.arguments)
                    res_str = str(res)
                except Exception as e:
                    res_str = f"Error executing tool '{tc.name}': {str(e)}"

                self.history.add_tool_response(tc.id, tc.name, res_str)

        return "I have executed the requested actions, sir. Anything else?"

    def _call_provider_with_retry(
        self,
        provider: BaseLLMProvider,
        messages: List[Dict[str, Any]],
    ) -> ProviderResponse:
        """
        Calls a provider with intelligent error recovery:
        - 400 tool failures: retries once with low temp (0.2), then once with core tool subset.
        - 413 payload too large: shrinks history and retries once.
        - 429 per-minute rate limits: extracts retry-after delay and retries up to max_retries.
        - 429 daily quota / 401 / 404 / 5xx: raises immediately for truthful error logging and fallback.
        """
        max_pm_retries = config.llm.per_minute_max_retries
        active_tools = self.local_tools_schema if provider.name.lower() == "ollama" else self.cloud_tools_schema

        is_first_ollama = (provider.name.lower() == "ollama" and not self._ollama_warmed)
        if is_first_ollama:
            self._ollama_warmed = True

        current_messages = list(messages)
        current_tools = active_tools
        current_temp = 0.7

        tool_retry_done = False
        subset_retry_done = False
        payload_retry_done = False
        pm_attempts = 0

        while True:
            try:
                t0 = time.perf_counter()
                try:
                    res = provider.chat(current_messages, tools=current_tools, temperature=current_temp)
                except TypeError:
                    res = provider.chat(current_messages, tools=current_tools)
                if is_first_ollama:
                    dur = time.perf_counter() - t0
                    try:
                        from jarvis.timing import tracker
                        tracker.record_stage("ollama_warmup", dur, f"model={provider.model_name}")
                    except Exception:
                        pass
                return res
            except Exception as exc:
                status_code, err_code, clean_msg = extract_error_info(exc)

                # 1. HTTP 400 tool failures (tool_use_failed, reasoning token length, or malformed arguments)
                is_tool_error = (
                    status_code == 400 and (
                        err_code in ("tool_use_failed", "failed_generation", "reasoning_length_limit")
                        or "tool" in clean_msg.lower()
                        or "function" in clean_msg.lower()
                    )
                )
                if is_tool_error:
                    if not tool_retry_done:
                        tool_retry_done = True
                        current_temp = 0.2
                        logger.warning(
                            f"{provider.name.capitalize()} tool call error (HTTP 400, code={err_code}). "
                            "Retrying once on same provider with low temperature (0.2)..."
                        )
                        continue
                    elif not subset_retry_done and current_tools != self.subset_tools_schema:
                        subset_retry_done = True
                        current_tools = self.subset_tools_schema
                        current_temp = 0.2
                        logger.warning(
                            f"{provider.name.capitalize()} tool call error persisted. "
                            "Retrying once on same provider with core tool subset..."
                        )
                        continue

                # 2. HTTP 413 Payload Too Large
                if status_code == 413 or "too large" in clean_msg.lower():
                    if not payload_retry_done and len(current_messages) > 3:
                        payload_retry_done = True
                        logger.warning(
                            f"{provider.name.capitalize()} payload too large (HTTP 413). "
                            "Shrinking conversation history and retrying once..."
                        )
                        system_msg = current_messages[0]
                        current_messages = [system_msg] + current_messages[-2:]
                        continue

                # 3. HTTP 429 Rate Limits (Differentiate per-minute retry vs daily exhaustion)
                if status_code == 429 or isinstance(exc, RateLimitError) or "429" in clean_msg:
                    is_daily = self.is_daily_quota_error(clean_msg)
                    retry_sec = extract_retry_after(exc)
                    if is_daily or (retry_sec and retry_sec >= 3600):
                        raise exc

                    if pm_attempts < max_pm_retries:
                        pm_attempts += 1
                        delay = retry_sec or config.llm.per_minute_backoff_seconds
                        logger.info(
                            f"{provider.name} per-minute limit hit (HTTP 429). "
                            f"Retrying in {delay}s (attempt {pm_attempts}/{max_pm_retries})..."
                        )
                        time.sleep(delay)
                        continue

                # Unrecoverable error on this provider -> raise for cooldown / fallback handling
                raise exc

    def _build_all_blocked_message(self) -> str:
        """Builds a helpful diagnostic error message when all providers are unavailable."""
        reasons = []
        for p in self.providers:
            is_avail, status_msg = p.is_available()
            if not is_avail:
                reasons.append(f"- {p.name.capitalize()}: {status_msg}")
            elif self.is_provider_blocked(p.name):
                blocked_time = self.blocked_until.get(p.name)
                time_str = blocked_time.strftime("%H:%M:%S") if blocked_time else "soon"
                reasons.append(f"- {p.name.capitalize()}: Temporarily in cooldown until {time_str} due to quota/network limits.")

        details = "\n".join(reasons) if reasons else "No provider could be contacted."
        err_msg = (
            "I apologize, sir, but all configured AI providers are currently unavailable:\n"
            f"{details}\n"
            "If using Ollama, ensure it is running with 'ollama serve' and the model is downloaded."
        )
        logger.error("All AI providers are currently unavailable.")
        return err_msg

    def reset(self) -> None:
        """Resets conversational history."""
        self.history.reset()
